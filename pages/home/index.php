<script>
    $(document).ready(function() {
        $('#contactUsForm').submit(function(e) {
            e.preventDefault();

            let isValid = true;

            $('#contactUsForm .form-control').removeClass('is-invalid');
            $('#message').html("");

            $('#contactUsForm .form-control').each(function() {
                if (!$(this).val().trim()) {
                    $(this).addClass('is-invalid');
                    isValid = false;

                    const fieldId = $(this).attr('id');
                    const label = $("label[for='" + fieldId + "']").text();

                    if ($('#message ul').length === 0) {
                        $('#message').html("<p class='text-danger'>Please complete the following:</p><ul class='text-danger'></ul>");
                    }
                    $('#message ul').append("<li>" + label + "</li>");
                }
            });

            if (isValid) {
                const $button = $('#contactUsForm button[type="submit"]');
                $button.prop('disabled', true);
                $button.html(`<span class="spinner-border spinner-border-sm me-2" role="status" aria-hidden="true"></span>Sending...`);

                $.ajax({
                    url: 'actions/contact-us.php',
                    type: 'POST',
                    data: $(this).serialize(),
                    success: function(response) {
                        setTimeout(() => {
                            $('#message')
                                .html(`<div class="alert alert-success">Thank you! Your message has been sent successfully.</div>`)
                                .children('.alert')
                                .delay(3000)
                                .fadeOut(1000, function() {
                                    $(this).remove();
                                });

                            $('#contactUsForm')[0].reset();
                            $('#contactUsForm .form-control').removeClass('is-invalid');

                            const $button = $('#contactUsForm button[type="submit"]');
                            $button.prop('disabled', false);
                            $button.html(`Send Message`);
                        }, 1500);
                    }
                })

            }
        });
    });

    $(document).ready(function() {
        // Open chat box when clicking the 'startChat' button
        $('#startChat').click(function() {
            $('#chatBox').removeClass('d-none');
            $('#namePrompt').removeClass('d-none'); // Ensure the name prompt is visible when chat is opened
            $('#chatWindow').addClass('d-none'); // Hide the chat window initially
            $('#cancelNameEntry').addClass('d-none'); // Hide Cancel button initially
        });

        // Close chat box
        $('#closeChat').click(function() {
            $('#chatBox').addClass('d-none');
        });

        let userName = '';

        // Start conversation after entering name
        $('#startConversation').click(function() {
            const nameInput = $('#username').val().trim();
            if (nameInput !== '') {
                userName = nameInput; // Set the userName to the entered name
                $('#namePrompt').addClass('d-none'); // Hide name input form
                $('#chatWindow').removeClass('d-none'); // Show chat window
                $('#chatMessages').html(`<div><small class="text-muted">Welcome, ${userName}!</small></div>`); // Reset chat and show welcome message
                $('#cancelNameEntry').removeClass('d-none'); // Show Cancel button after starting the conversation
            } else {
                alert('Please enter your name to start the chat.');
            }
        });

        // Cancel name input and restart the process
        $('#cancelNameEntry').click(function() {
            // Reset the userName variable so the next name entered will be treated as the new one
            userName = '';
            $('#username').val(''); // Clear the username input
            $('#chatMessages').html(''); // Clear the chat messages
            $('#namePrompt').removeClass('d-none'); // Show name input form again
            $('#chatWindow').addClass('d-none'); // Hide chat window
            $('#cancelNameEntry').addClass('d-none'); // Hide Cancel button
        });

        $('#sendMsg').click(function() {
            const msg = $('#chatInput').val().trim();
            if (msg !== '') {
                $('#chatMessages').append(`<div><strong>${userName}:</strong> ${msg}</div>`);
                $('#chatInput').val(''); // Clear the chat input field

                setTimeout(() => {
                    $('#chatMessages').append(`<div><strong>Admin:</strong> Thank you for reaching out!</div>`);
                    $('#chatMessages').scrollTop($('#chatMessages')[0].scrollHeight); // Scroll to the bottom of the chat window
                }, 1000);
            }
        });
    });


    function swapCompletedImages(mainImageId, thumbElement, thumbnailsContainerId) {
        const mainImg = document.getElementById(mainImageId);
        const currentMainSrc = mainImg.src;

        mainImg.src = thumbElement.src;

        const newThumb = document.createElement('img');
        newThumb.src = currentMainSrc;
        newThumb.alt = "Thumbnail";
        newThumb.className = "img-thumbnail thumb-img";
        newThumb.style.width = "60px";
        newThumb.style.height = "60px";
        newThumb.style.objectFit = "cover";
        newThumb.style.cursor = "pointer";
        newThumb.onclick = function() {
            swapCompletedImages(mainImageId, newThumb, thumbnailsContainerId);
        };

        thumbElement.parentNode.removeChild(thumbElement);

        document.getElementById(thumbnailsContainerId).appendChild(newThumb);
    }
</script>


